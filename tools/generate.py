"""
generate.py: write the files that are derived from constants/ and schema/.

    constants/constants.json  ->  python/bollardeck/constants.py
                                  js/bollardeck.constants.js
                                  the constants block inside js/bollardeck.js
    constants/makers.json     ->  python/bollardeck/device/_makers.py
    schema/*.schema.json      ->  python/bollardeck/_schemas.py
                                  js/bollardeck.schemas.js

    tools/generate.py           write them
    tools/generate.py --check   write nothing; exit 1 when any of them is stale (CI runs this)

Never edit a generated file: change the source and run this. Standard library only.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONSTANTS = ROOT / "constants" / "constants.json"
MAKERS = ROOT / "constants" / "makers.json"
SCHEMA_DIR = ROOT / "schema"
SCHEMA_SUFFIX = ".schema.json"
PY_CONSTANTS = ROOT / "python" / "bollardeck" / "constants.py"
PY_SCHEMAS = ROOT / "python" / "bollardeck" / "_schemas.py"
PY_MAKERS = ROOT / "python" / "bollardeck" / "device" / "_makers.py"
JS_CONSTANTS = ROOT / "js" / "bollardeck.constants.js"
JS_MAIN = ROOT / "js" / "bollardeck.js"
JS_SCHEMAS = ROOT / "js" / "bollardeck.schemas.js"
BEGIN = "  // BEGIN GENERATED CONSTANTS (tools/generate.py writes this block from constants/constants.json)"
END = "  // END GENERATED CONSTANTS"
NAME_RE = re.compile(r"^[A-Z][A-Z0-9_]*$")
NOTE = "GENERATED by tools/generate.py from %s. Do not edit: change the source and run the tool."


def read_constants():
    data = json.loads(CONSTANTS.read_text(encoding="utf-8"))
    if data.get("version") != 1 or not isinstance(data.get("constants"), dict):
        raise SystemExit("generate: %s is not a version 1 constants file" % CONSTANTS.name)
    for name, entry in data["constants"].items():
        if not NAME_RE.match(name):
            raise SystemExit("generate: constant name %r must be UPPER_CASE" % name)
        if set(entry) != {"value", "about"} or not str(entry["about"]).strip():
            raise SystemExit("generate: constant %s needs exactly a value and an about" % name)
    return data["constants"]


def py_literal(value):
    """A JSON value as an immutable-leaning Python literal: lists become tuples."""
    if isinstance(value, list):
        inner = ", ".join(py_literal(v) for v in value)
        return "(%s%s)" % (inner, "," if len(value) == 1 else "")
    if isinstance(value, dict):
        return "{%s}" % ", ".join("%s: %s" % (json.dumps(k), py_literal(v)) for k, v in value.items())
    if value is None or isinstance(value, bool):
        return repr(value)
    return json.dumps(value, ensure_ascii=False)


def wrap_comment(text, prefix):
    words, lines, line = text.split(), [], ""
    for word in words:
        if line and len(prefix) + len(line) + 1 + len(word) > 100:
            lines.append(prefix + line)
            line = word
        else:
            line = (line + " " + word).strip()
    return lines + ([prefix + line] if line else [])


def python_constants(constants):
    out = ["# SPDX-License-Identifier: Apache-2.0",
           "# " + NOTE % "constants/constants.json",
           '"""Values the Python and JavaScript bindings must agree on (js: bollardeck.constants)."""',
           ""]
    for name, entry in constants.items():
        out += wrap_comment(entry["about"], "# ")
        out.append("%s = %s" % (name, py_literal(entry["value"])))
        out.append("")
    out.append("__all__ = [%s]" % ", ".join(json.dumps(n) for n in constants))
    return "\n".join(out) + "\n"


def js_object(constants, indent):
    """The constants as the body of a JS object literal, one member per constant."""
    lines = []
    for name, entry in constants.items():
        lines += wrap_comment(entry["about"], indent + "// ")
        lines.append("%s%s: %s," % (indent, name, json.dumps(entry["value"], ensure_ascii=False)))
    return lines


FREEZE = [
    "function (value) {",
    "  // Freeze a constant all the way down, so no caller can change what the others read.",
    "  var freeze = function (v) {",
    '    if (v && typeof v === "object") { Object.keys(v).forEach(function (k) { freeze(v[k]); }); Object.freeze(v); }',
    "    return v;",
    "  };",
    "  return freeze(value);",
    "}",
]


def js_constants(constants):
    out = ["// SPDX-License-Identifier: Apache-2.0",
           "// " + NOTE % "constants/constants.json",
           "// The constants by themselves, for a page or a tool that wants nothing else: a <script> tag",
           "// defines globalThis.bollardeckConstants, and require() returns the same object.",
           "// bollardeck.js carries the same values as bollardeck.constants and does not need this file.",
           "(function (root) {",
           '  "use strict";',
           "  var deepFreeze = " + "\n  ".join(FREEZE) + ";",
           "  var constants = deepFreeze({"]
    out += js_object(constants, "    ")
    out += ["  });",
            '  if (typeof module === "object" && module.exports) {',
            "    module.exports = constants;",
            "  }",
            "  root.bollardeckConstants = constants;",
            '})(typeof globalThis !== "undefined" ? globalThis : this);']
    return "\n".join(out) + "\n"


def js_main(constants, current):
    """js/bollardeck.js with its generated block replaced."""
    if current.count(BEGIN) != 1 or current.count(END) != 1 or current.index(BEGIN) > current.index(END):
        raise SystemExit("generate: %s needs exactly one BEGIN/END GENERATED CONSTANTS block" % JS_MAIN.name)
    head, rest = current.split(BEGIN)
    _, tail = rest.split(END)
    block = [BEGIN,
             "  var deepFreeze = " + "\n  ".join(FREEZE) + ";",
             "  bollardeck.constants = deepFreeze({"]
    block += js_object(constants, "    ")
    block += ["  });", END]
    return head + "\n".join(block) + tail


def python_schemas():
    paths = sorted(SCHEMA_DIR.glob("*" + SCHEMA_SUFFIX))
    out = ["# SPDX-License-Identifier: Apache-2.0",
           "# " + NOTE % "schema/*.schema.json",
           '"""The platform\'s JSON Schemas as JSON text, by name. Read them through bollardeck.schema."""',
           "",
           "SCHEMAS = {"]
    for path in paths:
        name = path.name[: -len(SCHEMA_SUFFIX)]
        text = json.dumps(json.loads(path.read_text(encoding="utf-8")), ensure_ascii=True, separators=(",", ":"))
        out.append("    %s: (" % json.dumps(name))
        for i in range(0, len(text), 96):
            out.append("        %r" % text[i:i + 96])
        out.append("    ),")
    out.append("}")
    return "\n".join(out) + "\n"


def no_proto_keys(value, where):
    """A member called __proto__ in a JS object literal would set a prototype, not a member."""
    if isinstance(value, dict):
        if "__proto__" in value:
            raise SystemExit("generate: %s has a member called __proto__" % where)
        for item in value.values():
            no_proto_keys(item, where)
    elif isinstance(value, list):
        for item in value:
            no_proto_keys(item, where)


def js_schemas():
    """bollardeck.schemas for the browser: the parsed schemas by name, frozen all the way down, so
    a page can validate with bollardeck.schema without fetching anything."""
    out = ["// SPDX-License-Identifier: Apache-2.0",
           "// " + NOTE % "schema/*.schema.json",
           "// The platform's JSON Schemas by name, as bollardeck.schemas. Read them through bollardeck.schema.",
           "(function (root) {",
           '  "use strict";',
           "  var schemas = {"]
    for path in sorted(SCHEMA_DIR.glob("*" + SCHEMA_SUFFIX)):
        name = path.name[: -len(SCHEMA_SUFFIX)]
        body = json.loads(path.read_text(encoding="utf-8"))
        no_proto_keys(body, path.name)
        out.append("    %s: %s," % (json.dumps(name), json.dumps(body, ensure_ascii=True, separators=(",", ":"))))
    out += ["  };",
            "  var freeze = function (v) {",
            '    if (v && typeof v === "object") { Object.keys(v).forEach(function (k) { freeze(v[k]); }); Object.freeze(v); }',
            "    return v;",
            "  };",
            '  var bollardeck = (typeof root.bollardeck === "object" && root.bollardeck) ||',
            '    ((typeof module === "object" && module.exports && typeof require === "function") ? require("./bollardeck.js") : (root.bollardeck = {}));',
            "  bollardeck.schemas = freeze(schemas);",
            "  (bollardeck.parts || (bollardeck.parts = {})).schemas = true;",
            '  if (typeof module === "object" && module.exports) module.exports = bollardeck.schemas;',
            '})(typeof globalThis !== "undefined" ? globalThis : this);']
    return "\n".join(out) + "\n"


def python_makers():
    """The maker registry as JSON text, so the package carries it without package data."""
    text = json.dumps(json.loads(MAKERS.read_text(encoding="utf-8")), ensure_ascii=True, separators=(",", ":"))
    out = ["# SPDX-License-Identifier: Apache-2.0",
           "# " + NOTE % "constants/makers.json",
           '"""The maker registry (popboll.makers/1) as JSON text. Read it through bollardeck.device.identity."""',
           "",
           "REGISTRY_JSON = ("]
    for i in range(0, len(text), 96):
        out.append("    %r" % text[i:i + 96])
    out.append(")")
    return "\n".join(out) + "\n"


def outputs():
    constants = read_constants()
    return {
        PY_CONSTANTS: python_constants(constants),
        JS_CONSTANTS: js_constants(constants),
        JS_MAIN: js_main(constants, JS_MAIN.read_text(encoding="utf-8")),
        PY_SCHEMAS: python_schemas(),
        PY_MAKERS: python_makers(),
        JS_SCHEMAS: js_schemas(),
    }


def stale():
    """The generated files that do not match their sources, as repo-relative paths."""
    return [str(path.relative_to(ROOT)) for path, text in outputs().items()
            if not path.is_file() or path.read_text(encoding="utf-8") != text]


def main(argv=None):
    args = sys.argv[1:] if argv is None else argv
    if args not in ([], ["--check"]):
        print(__doc__.strip(), file=sys.stderr)
        return 2
    if args:
        old = stale()
        for rel in old:
            print("generate: %s is stale; run tools/generate.py" % rel, file=sys.stderr)
        return 1 if old else 0
    for path, text in outputs().items():
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            print("generate: wrote %s" % path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
